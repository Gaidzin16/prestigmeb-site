<div class="card help">
  <h2>Работы — фотографии ваших изделий</h2>
  <h3>Добавить фото</h3>
  <p>Вверху: выберите <b>Раздел</b> (Кухни, Шкафы-купе, Детские, Прихожие), нажмите
    «Выбрать файлы» — можно отметить сразу несколько — и «Загрузить». Фото с телефона
    подходят как есть: мы сами повернём и уменьшим. Новые фото встают <b>первыми</b>
    в портфолио.</p>

  <h3>Что означают поля в карточке</h3>
  <ul>
    <li><b>Цифра на фото</b> — какое место работа занимает в портфолио.</li>
    <li><b>Подпись (alt)</b> — одно предложение, что на фото: «Белая угловая кухня с
      деревянной столешницей». Её видят поисковики — так вас находят по картинкам.</li>
    <li><b>Раздел</b> — к какой категории относится работа. По нему работает фильтр
      на странице «Портфолио».</li>
    <li><b>Материал</b> — необязательно. Тоже фильтр на сайте: плёнка, пластик, эмаль,
      массив, рамочные.</li>
    <li><b>В портфолио</b> — галочка стоит: фото видно в общей ленте работ.
      Снимите, если фото нужно только на главной или вообще спрятать.</li>
    <li><b>Главная</b> — номер места в карусели на главной странице. Пусто — не
      показывать там. Поставьте 1 тому фото, которое должно быть первым, 2 — следующему
      и так далее.</li>
    <li><b>Категория</b> — номер места в ленте из четырёх фото на странице раздела
      (например, на странице «Кухни»). Пусто — не показывать. Номера 1–4.</li>
  </ul>

  <h3>Порядок и удаление</h3>
  <ul>
    <li>Стрелки <b>↑ ↓</b> двигают работу на одну позицию. На компьютере карточку можно
      перетаскивать мышью.</li>
    <li>Кнопки <b>Все / Кухни / Шкафы-купе …</b> — просто фильтр показа. Порядок работ
      они не меняют.</li>
    <li><b>✕</b> удаляет фото с сайта сразу, после подтверждения.</li>
    <li>Закончили — <b>«Сохранить все изменения»</b>.</li>
  </ul>
</div>

